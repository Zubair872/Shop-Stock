import { ref } from "vue";

const STORAGE_KEY = "shopstock_lang";
const VALID = new Set(["roman", "ur", "en"]);

function getInitialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return VALID.has(saved) ? saved : "roman";
  } catch {
    return "roman";
  }
}

export const lang = ref(getInitialLang());

function applyDocumentDir(code) {
  if (typeof document !== "undefined") {
    document.documentElement.dir = code === "ur" ? "rtl" : "ltr";
    document.documentElement.lang = code === "ur" ? "ur" : code === "en" ? "en" : "ur-Latn";
  }
}

applyDocumentDir(lang.value);

export function setLang(code) {
  if (!VALID.has(code)) return;
  lang.value = code;
  applyDocumentDir(code);
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    return;
  }
}

